# Пересборка скина интерфейса — деревянных 9-slice досок из Assets/Game/UI/Skin.
#
# Скрипт, нарисовавший первые четыре спрайта, был утерян, и полгода нельзя было добавить ни
# кнопки, ни вкладки: художника в проекте нет, а подобрать доску на глаз к уже нарисованной
# не выходит — она сложнее, чем кажется. Здесь модель снята обратно с самих PNG (гистограммы,
# автокорреляция, регрессия по каналам), и теперь скин снова растёт кодом, как иконки ресурсов
# в Tools/icons.py и декор в OnlineDecorIcons.cs.
#
# Запускать можно сколько угодно раз: шум сидирован поимённо, результат один и тот же.
#
#   python Tools/skin.py
#
# ---------------------------------------------------------------------------------------------
# Устройство доски (всё измерено, не выдумано)
#
#   1. Кромка — ровно 1 px по периметру, ОДИН фиксированный цвет на весь скин. Это тот клей,
#      который держит семью: сколько бы ни было тонов доски, обведены они одинаково.
#   2. Планки — горизонтальные доски высотой ph, шов в последней строке каждой. Планки через
#      одну светлее/темнее на 3%: сверху светлая. Умножением, а не прибавкой — иначе тёмная
#      панель получит тот же контраст, что светлая кнопка, и рассыплется на полосы.
#   3. Фаска — полоса вдоль периметра: верхняя половина в тени, нижняя в блике.
#   4. Шов и тень фаски — ОДИН И ТОТ ЖЕ полупрозрачный слой. Там, где шов попадает в фаску,
#      они складываются сами собой и дают тёмный уголок. В исходнике этот уголок есть
#      (114 при шве 123 и фаске 121), и повторяется он только так — перемножением слоёв.
#   5. Гвозди — 3x3 в углах: верхняя строка блик, две нижние тело. Цвета тоже фиксированные.
#      Гвоздь обязан целиком помещаться в УГЛОВУЮ зону 9-slice. В исходнике он стоял на
#      отступе кромка+фаска+2 и одним столбиком вылезал в замащиваемую середину — а середина
#      повторяется каждые 34 px, и широкая кнопка выходила перфорированной, как отрывной
#      талон. Поэтому отступ теперь кромка+фаска, без двух пикселей воздуха.
#
# Волокно — не умножение цвета, а прибавка тёплого сдвига (1, 0.80, 0.60). Так измерено во всех
# четырёх исходниках сразу: у коричневой доски ось волокна (1, 0.79, 0.60), у зелёной
# (1, 0.86, 0.62) — почти та же, хотя сами цвета разные. Умножай оно цвет, зелёная доска на
# светлых волокнах уезжала бы в кислотный, а тёмная панель теряла бы волокно вовсе.

import math
import pathlib
import random

from PIL import Image, ImageDraw, ImageFont

ROOT = pathlib.Path(__file__).resolve().parent.parent
SKIN = ROOT / "Assets/Game/UI/Skin"
PREVIEW = ROOT / "Tools/skin-preview.png"
# Четыре доски, нарисованные утерянным скриптом, — как есть, вне Assets. Сверяться с
# Assets нельзя: там уже лежит вывод этого скрипта, и отличие всегда выйдет нулевым.
REFERENCE = ROOT / "Tools/skin-reference"

# --- палитра -----------------------------------------------------------------------------------
# Числа сняты с исходных PNG: база планки = средний тон тёмной планки / 0.97.
# В скобках — модальный цвет, тот, что видно пипеткой; он лежит внутри разброса волокна.

EDGE = (61, 41, 23)            # кромка, одна на весь скин
NAIL_BODY = (46, 36, 28)       # тело гвоздя
NAIL_SHINE = (201, 189, 166)   # блик на шляпке

DOSKA = (139.5, 96.3, 60.4)    # кнопка в покое   (модальный 136,94,59)
DOSKA_HOVER = (163.0, 115.3, 75.2)  # она же под курсором: +17% (модальный 158,112,73)
GREEN = (112.2, 142.4, 75.8)   # согласная кнопка (модальный 106,136,72)
PANEL = (75.7, 52.3, 34.4)     # панель окна      (модальный 77,53,35)

# Дорисованное. Тона выбраны в той же светлоте, что и снятые, — семья держится не оттенком,
# а тем, что доска везде одной яркости и одной кромки.
GREEN_HOVER = tuple(c * 1.17 for c in GREEN)   # то же осветление, что у коричневой
DANGER = (152.0, 79.0, 58.0)   # морёная в красный: необратимое действие
TAB = (98.0, 68.0, 44.0)       # вкладка в покое — темнее кнопки, светлее панели
RIBBON = (98.0, 68.0, 44.0)    # лента-заголовок

# Гнездо и жёлоб рисуются НА цвете панели, а не своим тоном: это дырка в панели, а не
# отдельная деталь. Ободок остаётся панельным, а поле внутри проваливается множителем well —
# ступенька между ними и есть край дырки, обводить её нечем.

# --- измеренные коэффициенты -------------------------------------------------------------------
PLANK_TINT = 0.055     # планки через одну на ±5.5%
SHADOW_TONE = 0.775    # цвет тени = база * 0.775
SHADOW_ALPHA = 0.58    # ...положенный с такой непрозрачностью
LIGHT_TONE = 1.18      # цвет блика = база * 1.18
LIGHT_ALPHA = 0.45
GRAIN_DIR = (1.0, 0.80, 0.60)  # тёплый сдвиг волокна
GRAIN_SD = 11.0        # разброс волокна в уровнях НА ЯРКОСТИ КНОПКИ; тёмным доскам — доля
GRAIN_SMEAR = 0.19     # затяжка волокна вдоль доски: даёт замеренную корреляцию соседей 0.17
FIBRE = 3.2            # длинное волокно поперёк — две синусоиды по y, амплитуда в уровнях

# Почему волокно втрое громче снятого с исходников (было 3.95 при разбросе 0.03 планки):
# у панели середина замащивается, и на экране она шла разбросом яркости 2.3 из 255 — меньше
# процента, ниже порога различения. Деревянный скин при этом работал как обычная заливка:
# нарисованное дерево до глаза не доходило вовсе. Числа подняты до той громкости, при которой
# доска читается доской в родном масштабе 1:1, и ни на шаг дальше — дальше начинается грязь.

# Шов между планками разложен на две строки: тёмная (сама щель) и светлая под ней (кромка
# следующей доски ловит свет). Одной тёмной строки не хватало — щель без блика читается
# царапиной, а не стыком двух досок.
SEAM_LIGHT_ALPHA = 0.30

# Волокно берётся долей от яркости доски, а не одними и теми же уровнями на всех.
# Исходники мерились так, будто разброс общий, — и на тёмной панели (яркость 54 против 99
# у кнопки) те же уровни дают вдвое больший ОТНОСИТЕЛЬНЫЙ контраст: доска перестаёт быть
# доской и читается наждаком. Опорная яркость — кнопка в покое, на ней число и подбиралось.
GRAIN_REF = sum(DOSKA) / 3.0


def mix(a, b, t):
    """Положить цвет b поверх a с непрозрачностью t."""
    return tuple(a[i] + (b[i] - a[i]) * t for i in range(3))


def scale(c, k):
    return tuple(v * k for v in c)


def grain_field(w, h, seed, k=1.0):
    """
    Поле волокна: белый шум, слегка затянутый вдоль доски, плюс длинная синусоида поперёк.

    Затяжка обязательна. Спрайты режутся 9-slice и середина у них не растягивается, а
    замащивается (-unity-slice-type: tiled в GameHud.uss), но всё равно повторяется куском в
    34 px — чистый пиксельный шум на таком куске читается как грязь, а затянутый вдоль
    волокна — как доска.
    """
    rnd = random.Random(seed)
    raw = [[rnd.uniform(-1.0, 1.0) for _ in range(w)] for _ in range(h)]
    norm = GRAIN_SD * k / (0.5774 * math.sqrt(1.0 + GRAIN_SMEAR ** 2))

    # Фазы от того же зерна: две доски подряд не должны получить одинаковый рисунок волокна.
    p1, p2 = rnd.uniform(0, 6.28), rnd.uniform(0, 6.28)

    field = []
    for y in range(h):
        fibre = FIBRE * k * (0.55 * math.sin(y * 0.83 + p1) + 0.45 * math.sin(y * 0.31 + p2))
        row = []
        for x in range(w):
            left = raw[y][x - 1] if x else raw[y][x]
            row.append((raw[y][x] + GRAIN_SMEAR * left) * norm + fibre)
        field.append(row)
    return field


def board(w, h, base, plank, bevel, nails, recessed, seed, well=1.0):
    """
    Одна доска скина. plank — высота планки (0 = цельная доска без швов),
    bevel — ширина фаски, recessed — перевернуть свет: тогда доска читается не выпуклой,
    а вдавленной (гнездо, жёлоб), well — во сколько провалить поле внутри фаски.
    """
    shadow = scale(base, SHADOW_TONE)
    light = scale(base, LIGHT_TONE)

    # Волокно долей от яркости доски (см. GRAIN_REF) — вместе с длинной фиброй: та же
    # громкость на тёмной панели читалась бы полосатым матрасом, а не деревом.
    field = grain_field(w, h, seed, (sum(base) / 3.0) / GRAIN_REF)

    image = Image.new("RGBA", (w, h))
    px = image.load()

    for y in range(h):
        # Планка: сверху светлая, дальше через одну.
        idx = (y // plank) if plank else 0
        tint = 1.0 + (PLANK_TINT if idx % 2 == 0 else -PLANK_TINT)
        seam = bool(plank) and (y % plank) == plank - 1
        seam_light = bool(plank) and (y % plank) == 0 and y > 0

        for x in range(w):
            if x == 0 or y == 0 or x == w - 1 or y == h - 1:
                px[x, y] = EDGE + (255,)
                continue

            on_bevel = (x <= bevel or x >= w - 1 - bevel
                        or y <= bevel or y >= h - 1 - bevel)

            g = field[y][x]
            k = tint if on_bevel else tint * well
            c = tuple(base[i] * k + g * GRAIN_DIR[i] for i in range(3))

            # Шов — тот же слой тени, что и у фаски: в углу они лягут друг на друга.
            if seam:
                c = mix(c, shadow, SHADOW_ALPHA)
            elif seam_light:
                c = mix(c, light, SEAM_LIGHT_ALPHA)

            # Край дырки: одна тёмная строчка сразу за фаской. Без неё провал поля читается
            # как пятно другого дерева, а не как гнездо, — ступеньки тона на это не хватает.
            if well < 1.0 and not on_bevel and (x == bevel + 1 or x == w - 2 - bevel
                                                or y == bevel + 1 or y == h - 2 - bevel):
                c = mix(c, shadow, SHADOW_ALPHA)

            if on_bevel:
                upper = y < h / 2
                if upper != recessed:
                    c = mix(c, shadow, SHADOW_ALPHA)
                else:
                    c = mix(c, light, LIGHT_ALPHA)

            px[x, y] = tuple(max(0, min(255, round(v))) for v in c) + (255,)

    if nails:
        # Кромка + фаска, без воздуха: гвоздь 3x3 обязан лечь целиком в угол 9-slice
        # (см. шапку файла). Воздух в два пикселя выносил третий столбик в замащиваемую
        # середину, и она печатала его через каждые 34 px по всей ширине кнопки.
        inset = 1 + bevel
        for nx in (inset, w - 3 - inset):
            for ny in (inset, h - 3 - inset):
                for dx in range(3):
                    px[nx + dx, ny] = NAIL_SHINE + (255,)
                    px[nx + dx, ny + 1] = NAIL_BODY + (255,)
                    px[nx + dx, ny + 2] = NAIL_BODY + (255,)
    return image


