def compare(name, image):
    """Среднее отличие от эталона — по всем каналам, в уровнях."""
    old = REFERENCE / f"{name}.png"
    if not old.exists():
        return None
    a = Image.open(old).convert("RGB")
    if a.size != image.size:
        return None
    b = image.convert("RGB")
    ap, bp = a.load(), b.load()
    total = 0
    for y in range(a.size[1]):
        for x in range(a.size[0]):
            total += sum(abs(ap[x, y][i] - bp[x, y][i]) for i in range(3))
    return total / (a.size[0] * a.size[1] * 3)


# --- контрольный лист --------------------------------------------------------------------------

def nine_slice(image, border, tw, th):
    """
    Собрать спрайт в размер так, как это делает UI Toolkit: углы как есть, края и середина —
    замащиванием (-unity-slice-type: tiled). Нужно, чтобы смотреть на скин глазами в том виде,
    в каком его увидит игрок, а не на исходную плитку.
    """
    w, h = image.size
    l, b, r, t = border
    out = Image.new("RGBA", (tw, th))

    xs = [(0, l, 0, l), (l, w - r, l, tw - r), (w - r, w, tw - r, tw)]
    ys = [(0, t, 0, t), (t, h - b, t, th - b), (h - b, h, th - b, th)]

    for sy0, sy1, dy0, dy1 in ys:
        for sx0, sx1, dx0, dx1 in xs:
            if sx1 <= sx0 or sy1 <= sy0 or dx1 <= dx0 or dy1 <= dy0:
                continue
            tile = image.crop((sx0, sy0, sx1, sy1))
            for y in range(dy0, dy1, sy1 - sy0):
                for x in range(dx0, dx1, sx1 - sx0):
                    out.alpha_composite(tile.crop((0, 0, min(sx1 - sx0, dx1 - x),
                                                   min(sy1 - sy0, dy1 - y))), (x, y))
    return out


def sheet_font():
    """Встроенный шрифт Pillow не знает кириллицы — подписи вышли бы квадратами."""
    for path in ("C:/Windows/Fonts/segoeui.ttf", "C:/Windows/Fonts/arial.ttf",
                 "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"):
        if pathlib.Path(path).exists():
            return ImageFont.truetype(path, 13)
    return ImageFont.load_default()


def preview(made):
    font = sheet_font()
    row_h, pad = 108, 14
    sheet = Image.new("RGBA", (940, pad + len(made) * row_h), (38, 30, 24, 255))
    draw = ImageDraw.Draw(sheet)

    for i, (name, image, border, diff) in enumerate(made):
        y = pad + i * row_h
        w, h = image.size
        label = f"{name}  {w}x{h}  border {border}"
        if diff is not None:
            label += f"  отличие от старого {diff:.1f}"
        draw.text((14, y), label, font=font, fill=(214, 196, 170, 255))

        # Плитка как есть, увеличенная нацело: видно каждый пиксель — волокно, фаску, гвозди.
        k = max(1, 96 // max(w, h))
        raw = image.resize((w * k, h * k), Image.NEAREST)
        sheet.alpha_composite(raw, (14, y + 16))

        # Она же, собранная в реальный размер: так спрайт увидит игрок.
        sheet.alpha_composite(nine_slice(image, border, 300, 76), (140, y + 16))
        # И вытянутая вдвое шире — проверка, что замащивание не рвёт рисунок.
        sheet.alpha_composite(nine_slice(image, border, 470, 40), (456, y + 34))

    sheet.convert("RGB").save(PREVIEW)


def main():
    made = []
    for name, w, h, base, plank, bevel, nails, recessed, border, seed, well in SPRITES:
        image = board(w, h, base, plank, bevel, nails, recessed, seed, well)
        diff = compare(name, image)
        image.save(SKIN / f"{name}.png")
        made.append((name, image, border, diff))
        note = f"  (отличие от старого {diff:.2f} уровня)" if diff is not None else ""
        print(f"{name:24s} {w}x{h} border={border}{note}")

    preview(made)
    print(f"\nконтрольный лист: {PREVIEW}")


main()
