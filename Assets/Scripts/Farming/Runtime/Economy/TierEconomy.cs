using UnityEngine;

namespace Farm.Farming
{
    /// <summary>
    /// Одна кривая на всю лестницу прогрессии.
    /// <para>
    /// Это ответ на «система ступеней — это куча работы»: работа не в том, чтобы строить,
    /// а в том, чтобы вручную набивать цены, урожаи и тайминги для каждой ступени. Здесь
    /// ступень — одно число, всё остальное выводится, поэтому добавить медь→железо→мифрил
    /// стоит один ассет и одну цифру, а не таблицу, которую никто не удержит в балансе.
    /// </para>
    /// <para>
    /// Числа остаются записанными в ассетах, а не считаются в рантайме — дизайнер должен
    /// иметь право переопределить любое отдельное значение, не воюя с формулой.
    /// <b>Поэтому правка констант здесь ничего не балансирует сама по себе:</b> это справочник,
    /// по которому ассеты пересчитываются разово. Меняешь кривую — пересчитывай ассеты.
    /// </para>
    /// </summary>
    public static class TierEconomy
    {
        /// <summary>Во сколько раз каждая ступень ценнее предыдущей — то есть шаг цены продажи.</summary>
        public const float ValueStep = 2.8f;

        /// <summary>
        /// Во сколько раз дорожает <b>покупка</b> следующей ступени.
        /// <para>
        /// Обязан быть больше <see cref="ValueStep"/>, и это главное число всей прогрессии.
        /// Пока они были равны (оба 2.8), «сколько текущего ресурса нужно, чтобы открыть
        /// следующий» оставалось константой ~19 на всех восьми ступенях: и медь→железо, и
        /// адамант→звёздный металл стоили одинаково в единицах труда. Лестница была
        /// прайс-листом. Отношение 4.5/2.8 = 1.6 значит, что каждая следующая рунга стоит
        /// в 1.6 раза больше труда, чем предыдущая: 30 единиц на первой, ~517 на седьмой.
        /// </para>
        /// </summary>
        public const float PriceStep = 4.5f;

        /// <summary>И во сколько дольше производится. Нарочно мягче шага ценности:
        /// высокие ступени обязаны окупать ожидание, иначе никто не полезет вверх.</summary>
        public const float TimeStep = 1.65f;

        /// <summary>Во сколько раз дорожает золотая часть каждого следующего уровня постройки.
        /// Быстрее шага материалов — чтобы золото не переставало иметь значение.</summary>
        public const float UpgradeGoldStep = 2.3f;

        /// <summary>Во сколько раз растёт материальная часть цены с каждым уровнем постройки.</summary>
        public const float UpgradeMaterialStep = 1.55f;

        public static int SellPrice(int tier, int baseValue = 3) =>
            Mathf.Max(1, Mathf.RoundToInt(baseValue * Mathf.Pow(ValueStep, Mathf.Max(0, tier - 1))));

        /// <summary>
        /// Сколько секунд растёт ступень. База согласована с длиной суток: сутки идут 600 секунд,
        /// светлого времени в них около 288, и культура первой ступени успевает за него примерно
        /// шесть циклов. Меняешь длину суток — меняй и её, иначе день перестанет быть «одним
        /// рабочим днём».
        /// <para>
        /// База была 24 секунды (дюжина циклов за день) — ферма тикала слишком часто, чтобы
        /// хоть что-то, кроме сбора, успевало победить в оценках фермера.
        /// </para>
        /// </summary>
        public static float GrowSeconds(int tier, float baseSeconds = 48f) =>
            baseSeconds * Mathf.Pow(TimeStep, Mathf.Max(0, tier - 1));

        /// <summary>
        /// Онлайн-тайминги: сколько РЕАЛЬНЫХ секунд растёт ступень в онлайн-версии.
        /// <para>
        /// Таблица ручная, а не степенная, — как в старых социальных фермах: у низких ступеней
        /// шаг крупный (5 → 15 → 40 минут: новичку важно почувствовать разницу), у высоких он
        /// выполаживается к «зашёл утром — собрал вечером» (8 → 12 часов), потому что дальше
        /// суток ждать не согласится никто. <see cref="TimeStep"/> тут не участвует: он
        /// остался от одиночной линии, где сутки шли 240 секунд.
        /// </para>
        /// <para>
        /// Как и всё в этом файле — справочник для разового пересчёта ассетов
        /// (Farm → Онлайн → Пересчитать тайминги роста), а не рантайм-формула.
        /// </para>
        /// </summary>
        public static float OnlineGrowSeconds(int tier)
        {
            switch (Mathf.Clamp(tier, 1, 8))
            {
                case 1: return 5f * 60f;          // 5 минут — первый круг цикла за одну сессию
                case 2: return 15f * 60f;
                case 3: return 40f * 60f;
                case 4: return 90f * 60f;         // полтора часа
                case 5: return 3f * 3600f;
                case 6: return 5f * 3600f;
                case 7: return 8f * 3600f;        // «посадил утром — собрал после работы»
                default: return 12f * 3600f;      // ступень 8, дальше суток не ждёт никто
            }
        }

        /// <summary>Цена в золоте грядки или жилы, производящей эту ступень.</summary>
        public static int PlotPrice(int tier, int basePrice = 20) =>
            Mathf.Max(1, Mathf.RoundToInt(basePrice * Mathf.Pow(PriceStep, Mathf.Max(0, tier - 1))));

        /// <summary>
        /// Жалование фермера за сутки найма (Ф3). Число рассчитано на то, что наём окупается
        /// фермой с полудюжиной низких грядок, но не превращается в фон: игрок платит заметно
        /// и решает, а не ставит галочку навсегда. Читается в рантайме — это цена услуги,
        /// а не записанный в ассет баланс.
        /// </summary>
        public const int FarmerWagePerDay = 150;

        /// <summary>
        /// Сколько единиц ресурса предыдущей ступени просит товар этой ступени сверх золота.
        /// Растёт медленнее цены: ресурс — второй ключ к ступени, а не второе золото.
        /// </summary>
        public static int LadderMaterials(int tier, int baseAmount = 10) =>
            Mathf.Max(1, Mathf.RoundToInt(baseAmount * Mathf.Pow(1.6f, Mathf.Max(0, tier - 2))));

        /// <summary>
        /// Золотая часть улучшения постройки. Уровень 1 — это сама постройка.
        /// </summary>
        public static int UpgradeGold(int level, int baseGold = 120) =>
            Mathf.Max(1, Mathf.RoundToInt(baseGold * Mathf.Pow(UpgradeGoldStep, Mathf.Max(0, level - 1))));

        /// <summary>Сколько единиц материала ступени N стоит улучшение до <paramref name="level"/>.</summary>
        public static int UpgradeMaterials(int level, int baseAmount = 12) =>
            Mathf.Max(1, Mathf.RoundToInt(baseAmount * Mathf.Pow(UpgradeMaterialStep, Mathf.Max(0, level - 1))));

        /// <summary>
        /// Материал какой ступени требует улучшение до <paramref name="level"/>.
        /// Уровни 1-2 просят ступень 1, уровни 3-4 — ступень 2 и так далее: новая ступень
        /// каждые два уровня гонит игрока вверх по производственной лестнице, а не по
        /// бесконечному гринду одного ресурса.
        /// </summary>
        public static int RequiredTier(int level) => Mathf.Max(1, (level + 1) / 2);

        /// <summary>
        /// Какую долю потребности закрывает один визит. Уровень 1 — перекус, максимальный —
        /// полный обед: смысл прокачки в том, чтобы фермера реже отвлекало, а не в большей цифре.
        /// </summary>
        public static float ServiceEfficiency(int level) => Mathf.Min(1f, 0.35f + (level - 1) * 0.22f);

        /// <summary>
        /// Во сколько раз быстрее работает мастерская этого уровня.
        /// <para>
        /// Не ограничена сверху там, где <see cref="ServiceEfficiency"/> упирается в единицу:
        /// кухня может наполнить шкалу лишь однажды, поэтому её лестница коротка, а у лесопилки
        /// потолка нет и её уровни обязаны продолжать окупаться. Поэтому у мастерских шесть
        /// ступеней, а у сервисных построек четыре.
        /// </para>
        /// </summary>
        public static float WorkshopSpeed(int level) => 1f + (Mathf.Max(1, level) - 1) * 0.55f;

        /// <summary>Доля, которую рынок добавляет к каждой продаже. Уровень 1 — +8%.</summary>
        public static float MarketBonus(int level) => Mathf.Max(0, level) * 0.08f;

        /// <summary>
        /// Насколько усиливает ферму постройка-усилитель этого уровня.
        /// <para>
        /// Линейно, в отличие от цены. Это осознанный перекос: цена растёт в
        /// <see cref="UpgradeGoldStep"/> раз за уровень, а польза — на постоянную величину,
        /// поэтому каждый следующий уровень окупается хуже предыдущего. Так усилители остаются
        /// выбором («во что вложиться сейчас»), а не обязательной лестницей, которую всё равно
        /// проходят до конца.
        /// </para>
        /// </summary>
        public static float Boost(int level, float perLevel) => perLevel * Mathf.Max(1, level);
    }
}
